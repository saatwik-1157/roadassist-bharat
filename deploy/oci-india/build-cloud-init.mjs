#!/usr/bin/env node
// Builds cloud-init.yaml from the files beside it, so the text cloud-init
// writes on the VM is byte-for-byte the text reviewed in the repository.
//
//   node deploy/oci-india/build-cloud-init.mjs           # rewrite cloud-init.yaml
//   node deploy/oci-india/build-cloud-init.mjs --check   # fail if it is stale
//
// Edit compose.yml, Caddyfile, db-init/10-roadassist-roles.sh or bootstrap.sh,
// never cloud-init.yaml by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "cloud-init.yaml");

const FILES = [
  { src: "Caddyfile", dest: "/opt/roadassist/Caddyfile", mode: "0644" },
  { src: "compose.yml", dest: "/opt/roadassist/compose.yml", mode: "0644" },
  { src: "db-init/10-roadassist-roles.sh", dest: "/opt/roadassist/db-init/10-roadassist-roles.sh", mode: "0755" },
  { src: "bootstrap.sh", dest: "/usr/local/sbin/roadassist-bootstrap.sh", mode: "0755" },
];

const HEADER = `#cloud-config
# RoadAssist Bharat on one OCI Always Free Ampere A1 VM (India region).
#
# GENERATED by build-cloud-init.mjs from the files beside it - do not edit by
# hand. Paste this WHOLE file into "Advanced options -> Management ->
# Initialization script -> Paste cloud-init script" when creating the instance
# (README step b). Shape VM.Standard.A1.Flex; image Canonical Ubuntu 24.04
# aarch64 (recommended) or Oracle Linux 9 aarch64.
#
# On first boot it writes compose.yml, Caddyfile and the database's first-start
# script into /opt/roadassist, then runs bootstrap.sh: opens 80/443 in the HOST
# firewall (OCI's images block them; the VCN security list is a separate
# firewall you open in the console), installs Docker + compose from Docker's
# own repository, clones the repository (for least-privilege-role.sql,
# backup.sh and migrate-db.sh) and pre-pulls the images.
#
# It holds NO secrets and does NOT start anything: /opt/roadassist/.env does not
# exist yet. You write it over SSH (README step c).
# Progress and errors: /var/log/roadassist-bootstrap.log
`;

function block({ src, dest, mode }) {
  const text = readFileSync(join(HERE, src), "utf8").replace(/\r\n/g, "\n");
  if (!text.endsWith("\n")) throw new Error(`${src} must end with a newline`);
  const body = text
    .split("\n")
    .slice(0, -1)
    .map((l) => (l.length ? "      " + l : ""))
    .join("\n");
  return `  - path: ${dest}\n    permissions: "${mode}"\n    content: |\n${body}\n`;
}

const yaml =
  HEADER +
  "\nwrite_files:\n" +
  FILES.map(block).join("\n") +
  "\nruncmd:\n  - [/usr/local/sbin/roadassist-bootstrap.sh]\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n");
  if (current !== yaml) {
    console.error("cloud-init.yaml is stale: run node deploy/oci-india/build-cloud-init.mjs");
    process.exit(1);
  }
  console.log(`cloud-init.yaml is current (${Buffer.byteLength(yaml)} bytes; OCI accepts up to 32,000)`);
} else {
  writeFileSync(OUT, yaml);
  console.log(`wrote cloud-init.yaml (${Buffer.byteLength(yaml)} bytes; OCI accepts up to 32,000)`);
}
